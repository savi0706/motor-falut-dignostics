#!/usr/bin/env python3
"""
pipeline/scripts/export_model.py
==================================
Converts a saved .tflite model to a C header file (model_data.h)
for inclusion in the ESP32-S3 firmware.

Usage:
    python scripts/export_model.py --tflite models/motor_fault_cnn.tflite

Output:
    ../firmware/include/model_data.h
"""

import argparse
import sys
from pathlib import Path


def tflite_to_c_header(tflite_path: Path, scaler_path: Path, header_path: Path):
    data = tflite_path.read_bytes()
    print(f"[INFO] Model size: {len(data)} bytes ({len(data)/1024:.1f} KB)")

    # Load scaler if available
    scaler_lines = []
    try:
        import joblib
        import numpy as np
        scaler = joblib.load(scaler_path)
        scaler_lines = [
            "",
            "// Feature normalization (StandardScaler from training)",
            "// Use: normalized[i] = (raw[i] - SCALER_MEAN[i]) / SCALER_STD[i]",
            f"const int SCALER_N_FEATURES = {len(scaler.mean_)};",
            f"const float SCALER_MEAN[{len(scaler.mean_)}] = {{",
            "  " + ", ".join(f"{v:.6f}f" for v in scaler.mean_) + "",
            "};",
            f"const float SCALER_STD[{len(scaler.scale_)}] = {{",
            "  " + ", ".join(f"{v:.6f}f" for v in scaler.scale_) + "",
            "};",
        ]
        print("[INFO] Scaler constants embedded in header")
    except Exception as e:
        print(f"[WARN] Could not embed scaler: {e}")

    lines = [
        "/* Auto-generated by pipeline/scripts/export_model.py",
        f" * Source: {tflite_path}",
        f" * Size: {len(data)} bytes",
        " * DO NOT EDIT — regenerate from training pipeline.",
        " */",
        "#pragma once",
        "#ifndef MODEL_DATA_H",
        "#define MODEL_DATA_H",
        "",
        f'#define MODEL_VERSION "cnn_v1"',
        f"#define MODEL_SIZE_BYTES {len(data)}",
    ] + scaler_lines + [
        "",
        f"// Model FlatBuffer ({len(data)} bytes)",
        "alignas(8) const unsigned char g_model_data[] = {",
    ]

    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")

    lines += [
        "};",
        f"const unsigned int g_model_data_len = {len(data)};",
        "",
        "#endif // MODEL_DATA_H",
    ]

    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text("\n".join(lines))
    print(f"[INFO] Written -> {header_path}")


def main():
    parser = argparse.ArgumentParser(description="Convert TFLite model to C header")
    parser.add_argument("--tflite",  default="models/motor_fault_cnn.tflite")
    parser.add_argument("--scaler",  default="models/scaler.pkl")
    parser.add_argument("--output",  default="../firmware/include/model_data.h")
    args = parser.parse_args()

    tflite_path = Path(args.tflite)
    if not tflite_path.exists():
        sys.exit(f"[ERROR] TFLite model not found: {tflite_path}\n"
                 f"        Run: python scripts/train_cnn.py")

    tflite_to_c_header(
        tflite_path,
        Path(args.scaler),
        Path(args.output)
    )
    print("[DONE]")


if __name__ == "__main__":
    main()
