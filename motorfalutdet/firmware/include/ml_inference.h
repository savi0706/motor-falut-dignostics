  #include "model_stub.h"
  #define MODEL_AVAILABLE 0
#endif

// ==================== INFERENCE RESULT ====================
struct InferenceResult {
    int    label;             // Winning class index (0–4)
    float  confidence;        // Softmax probability of winning class
    float  probs[NUM_CLASSES];// Full probability distribution
    bool   valid;             // false if inference failed
    uint32_t latency_us;      // inference time in microseconds
};

static const char* CLASS_NAMES[NUM_CLASSES] = {
    "Healthy",
    "Imbalance",
    "Misalignment",
    "Overload",
    "Friction"
};

// ==================== ENGINE ====================
class MLEngine {
public:
    MLEngine() : _initialized(false), _interpreter(nullptr) {}

    bool init() {
        static tflite::MicroErrorReporter micro_error_reporter;
        static tflite::AllOpsResolver resolver;

        _model = tflite::GetModel(g_model_data);
        if (_model->version() != TFLITE_SCHEMA_VERSION) {
            LOG_ERROR("TFLite model schema version mismatch!");
            return false;
        }

        static tflite::MicroInterpreter static_interp(
            _model,
            resolver,
            _tensor_arena,
            TFLITE_TENSOR_ARENA_SIZE,
            &micro_error_reporter,
            nullptr,
            nullptr
        );
        _interpreter = &static_interp;

        TfLiteStatus status = _interpreter->AllocateTensors();
        if (status != kTfLiteOk) {
            LOG_ERROR("TFLite AllocateTensors() failed");
            return false;
        }

        _input = _interpreter->input(0);
        LOG_INFO("TFLite engine OK. Input dims: [" +
                 String(_input->dims->data[0]) + "," +
                 String(_input->dims->data[1]) + "]");

#if MODEL_AVAILABLE == 0
        LOG_WARN("*** STUB MODEL IN USE — no real fault detection ***");
        LOG_WARN("    Export trained model to firmware/include/model_data.h");
#endif

        _initialized = true;
        return true;
    }

    InferenceResult run(const FeatureVector& fv) {
        InferenceResult res = {};
        res.valid = false;

        if (!_initialized || !fv.valid) return res;

        // --- Copy features into input tensor ---
        // Model expects shape [1, FEATURE_COUNT] float32
        if (_input->dims->data[1] != FEATURE_COUNT) {
            LOG_ERROR("Model input size mismatch: expected " +
                      String(FEATURE_COUNT) + " got " +
                      String(_input->dims->data[1]));
            return res;
        }
        for (int i = 0; i < FEATURE_COUNT; i++) {
#if MODEL_AVAILABLE
            float std_val = (SCALER_STD[i] > 1e-6f) ? SCALER_STD[i] : 1.0f;
            _input->data.f[i] = (fv.data[i] - SCALER_MEAN[i]) / std_val;
#else
            _input->data.f[i] = fv.data[i];
#endif
        }

        // --- Run inference ---
        uint32_t t0 = micros();
        TfLiteStatus status = _interpreter->Invoke();
        res.latency_us = micros() - t0;

        if (status != kTfLiteOk) {
            LOG_ERROR("TFLite Invoke() failed");
            return res;
        }

        // --- Parse output ---
        TfLiteTensor* output = _interpreter->output(0);
        float best_prob = -1.0f;
        int   best_idx  = 0;
        for (int i = 0; i < NUM_CLASSES; i++) {
            res.probs[i] = output->data.f[i];
            if (res.probs[i] > best_prob) {
                best_prob = res.probs[i];
                best_idx  = i;
            }
        }

        res.label      = best_idx;
        res.confidence = best_prob;
        res.valid      = true;

        LOG_DEBUG("ML → " + String(CLASS_NAMES[best_idx]) +
                  " (" + String(best_prob * 100.0f, 1) + "%) " +
                  String(res.latency_us) + " µs");

        return res;
    }

    bool is_ready() const { return _initialized; }

private:
    bool                     _initialized;
    const tflite::Model*     _model;
    tflite::MicroInterpreter* _interpreter;
    TfLiteTensor*            _input;
    uint8_t                  _tensor_arena[TFLITE_TENSOR_ARENA_SIZE];
};

// ==================== FAULT CLASSIFICATION WITH CONFIRMATION ====================
class FaultClassifier {
public:
    FaultClassifier() : _confirm_count(0), _confirmed_label(LABEL_HEALTHY) {}

    // Returns confirmed label (requires FAULT_CONFIRM_COUNT consecutive detections)
    int update(const InferenceResult& res) {
        if (!res.valid) return _confirmed_label;

        int raw_label = (res.confidence >= CONFIDENCE_THRESHOLD)
                        ? res.label
                        : LABEL_HEALTHY;

        if (raw_label != LABEL_HEALTHY) {
            _confirm_count++;
        } else {
            _confirm_count = 0;
            _confirmed_label = LABEL_HEALTHY;
        }

        if (_confirm_count >= FAULT_CONFIRM_COUNT) {
            _confirmed_label = raw_label;
        }

        return _confirmed_label;
    }

    int confirmed_label() const { return _confirmed_label; }
    const char* confirmed_name() const { return CLASS_NAMES[_confirmed_label]; }

private:
    uint8_t _confirm_count;
    int     _confirmed_label;
};

